-- ============================================================
-- 6. Alias/Synonym metadata (ไทย/อังกฤษ) เก็บผ่าน COMMENT ON
-- ใช้แทนการ hardcode TABLE_SYNONYMS / COLUMN_SYNONYMS ใน Python
-- รูปแบบ: คั่นแต่ละคำพ้องด้วย '|' (ไม่ต้องใส่ชื่อตาราง/คอลัมน์จริงซ้ำ เพราะโค้ดฝั่ง Python จะเติมให้อัตโนมัติ)
-- ============================================================
COMMENT ON TABLE suppliers IS 'ผู้จำหน่าย|ซัพพลายเออร์|supplier';
COMMENT ON TABLE warehouses IS 'คลังสินค้า|คลัง|warehouse';
COMMENT ON TABLE products IS 'สินค้า|product';
COMMENT ON TABLE inventory IS 'สต๊อก|สต็อก|คงเหลือ|stock';
COMMENT ON TABLE stock_movements IS 'ประวัติการเบิกจ่าย|ประวัติการเคลื่อนไหว|เบิกจ่าย|เคลื่อนไหวสินค้า|movement';

COMMENT ON COLUMN inventory.quantity IS 'จำนวนคงเหลือ|จำนวน';
COMMENT ON COLUMN stock_movements.quantity IS 'จำนวนคงเหลือ|จำนวน';
COMMENT ON COLUMN products.unit_price IS 'ราคาต่อหน่วย|ราคา|unit price';
COMMENT ON COLUMN warehouses.capacity IS 'ความจุ';

